#!/usr/bin/env node
// Check numbered WebP images; --write refreshes catalog URLs and gallery lists.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const catalogPath = path.join(root, 'assets/js/products-data.js');
const start = '// WATHBA_NUMBERED_IMAGES_START';
const end = '// WATHBA_NUMBERED_IMAGES_END';

function catalog() {
  const context = vm.createContext({window: {}});
  vm.runInContext(fs.readFileSync(catalogPath, 'utf8'), context);
  return vm.runInContext('products', context);
}

function dimensions(data) {
  if (data.length < 30 || data.toString('ascii', 0, 4) !== 'RIFF' || data.toString('ascii', 8, 12) !== 'WEBP' || data.readUInt32LE(4) + 8 !== data.length) return null;
  const chunk = data.toString('ascii', 12, 16);
  if (chunk === 'VP8X') return [data.readUIntLE(24, 3) + 1, data.readUIntLE(27, 3) + 1];
  if (chunk === 'VP8L' && data[20] === 0x2f) {
    const bits = data.readUInt32LE(21);
    return [(bits & 0x3fff) + 1, ((bits >>> 14) & 0x3fff) + 1];
  }
  if (chunk === 'VP8 ' && data[23] === 0x9d && data[24] === 1 && data[25] === 0x2a) return [data.readUInt16LE(26) & 0x3fff, data.readUInt16LE(28) & 0x3fff];
  return null;
}

function scanImages(options = {}) {
  const products = catalog();
  if (options.product && !products.some(p => p.id === options.product)) throw Error('Unknown product: ' + options.product);
  const sourcePath = path.join(root, 'scripts/temporary-image-sources.json');
  const temporaryHashes = new Set(fs.existsSync(sourcePath) ? JSON.parse(fs.readFileSync(sourcePath, 'utf8')).sources.map(s => s.sha256) : []);
  const result = {rows: [], errors: [], warnings: [], images: {}};
  const base = path.join(root, 'assets/images/products');
  if (fs.existsSync(base)) for (const folder of fs.readdirSync(base, {withFileTypes: true})) {
    if (folder.isDirectory() && !products.some(p => p.id === folder.name)) result.errors.push('Unknown product folder: ' + folder.name);
  }
  for (const product of products.filter(p => !options.product || p.id === options.product)) {
    const relative = 'assets/images/products/' + product.id;
    const folder = path.join(root, relative);
    const items = fs.existsSync(folder) ? fs.readdirSync(folder, {withFileTypes: true}) : [];
    const names = items.map(item => item.name);
    const valid = items.filter(item => item.isFile() && /^[1-9]\d*\.webp$/.test(item.name)).map(item => item.name).sort((a,b) => parseInt(a) - parseInt(b));
    const folded = new Set();
    for (const item of items) {
      const foldedName = item.name.toLowerCase();
      if (folded.has(foldedName)) result.errors.push(relative + ': duplicate name on Windows: ' + item.name);
      folded.add(foldedName);
      if (!item.isFile() || !/^[1-9]\d*\.webp$/.test(item.name)) result.errors.push(relative + ': invalid filename: ' + item.name + ' (use 1.webp, 2.webp, ...)');
    }
    if (!names.includes('1.webp')) result.errors.push(relative + ': missing main image 1.webp');
    if (valid.some((name,index) => parseInt(name) !== index + 1)) result.errors.push(relative + ': numbering must be consecutive from 1 (no gaps)');
    result.images[product.id] = [];
    for (const name of valid) {
      const data = fs.readFileSync(path.join(folder, name));
      const size = dimensions(data);
      if (!size || size.some(n => n < 1)) {result.errors.push(relative + '/' + name + ': invalid/truncated WebP; renaming JPG is not conversion'); continue;}
      const hash = crypto.createHash('sha256').update(data).digest('hex');
      if (data.length > 800 * 1024) result.warnings.push(relative + '/' + name + ': over 800 KB; compress if possible');
      result.images[product.id].push({src: relative + '/' + name + '?v=' + hash.slice(0,12), temporary: temporaryHashes.has(hash), width: size[0], height: size[1]});
    }
    result.rows.push({Product: product.id, Name: product.name.ar, Photos: valid.length, Main: names.includes('1.webp') ? '1.webp' : 'MISSING', Temporary: result.images[product.id].filter(i => i.temporary).length});
  }
  return result;
}

function updateImageCatalog(options = {}) {
  const result = scanImages();
  if (result.errors.length) throw Error('Image checks failed:\n' + result.errors.join('\n'));
  const before = fs.readFileSync(catalogPath, 'utf8');
  const responsivePath = path.join(root,'scripts/responsive-images.json');
  const responsive = fs.existsSync(responsivePath) ? JSON.parse(fs.readFileSync(responsivePath,'utf8')) : {};
  for (const images of Object.values(result.images)) for (const image of images) {
    const entry = responsive[image.src.split('?')[0]];
    if (entry && entry.sha256 === crypto.createHash('sha256').update(fs.readFileSync(path.join(root,image.src.split('?')[0]))).digest('hex')) image.srcset = entry.srcset;
  }
  const block = `${start}\n// Generated by node scripts/product-images.js --write. Edit image files, not this block.\nconst WATHBA_NUMBERED_IMAGES = ${JSON.stringify(result.images, null, 2)};\nfor (const product of products) {\n    product.imageFolder = 'assets/images/products/' + product.id + '/';\n    product.images = WATHBA_NUMBERED_IMAGES[product.id] || [];\n    product.image = product.images[0]?.src || product.imageFolder + '1.webp';\n    product.gallery = product.images.slice(1).map(image => image.src);\n}\n${end}`;
  let after;
  if (before.includes(start)) {
    const from = before.indexOf(start), to = before.indexOf(end, from);
    if (to < 0) throw Error('Unclosed generated images block');
    after = before.slice(0, from) + block + before.slice(to + end.length);
  } else {
    const anchor = 'window.WATHBA_PRODUCTS = products;';
    if (!before.includes(anchor)) throw Error('Catalog insertion point missing');
    after = before.replace(anchor, block + '\n\n' + anchor);
  }
  if (after !== before) fs.writeFileSync(catalogPath, after);
  if (!options.quiet) console.log('Updated all product covers and galleries.');
  return result;
}

if (require.main === module) {
  try {
    const args = process.argv.slice(2);
    const productIndex = args.indexOf('--product');
    const product = productIndex >= 0 ? args[productIndex + 1] : undefined;
    if (productIndex >= 0 && (!product || product.startsWith('--'))) throw Error('Use --product followed by the folder name.');
    if (args.includes('--write') && product) throw Error('--write updates all products; use --product only for checking.');
    const unknown = args.filter((arg,index) => !['--write','--product'].includes(arg) && !(productIndex >= 0 && index === productIndex + 1));
    if (unknown.length) throw Error('Unknown option: ' + unknown.join(' '));
    const result = args.includes('--write') ? updateImageCatalog() : scanImages({product});
    console.table(result.rows);
    for (const message of result.warnings) console.warn('WARNING: ' + message);
    for (const message of result.errors) console.error('ERROR: ' + message);
    console.log(`Products: ${result.rows.length} | Images: ${result.rows.reduce((n,r) => n + r.Photos,0)} | Errors: ${result.errors.length}`);
    if (result.errors.length) process.exitCode = 1;
  } catch(error) {console.error(error.message); process.exitCode = 1;}
}

module.exports = {scanImages, updateImageCatalog, dimensions};
